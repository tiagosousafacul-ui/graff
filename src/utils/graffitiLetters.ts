export function generateWordPolygons(
  word: string,
  canvasWidth = 1000,
  baselineY = 170,
  targetHeight = 260
): LetterPolygon[] {
  const cleanWord = word.trim().toUpperCase() || '3D';
  const chars = cleanWord.split('').slice(0, 6); // Max 6 chars for ideal composition width

  const count = chars.length;
  // Compute spacing
  const letterTargetWidth = Math.min(220, (canvasWidth - 160) / count - 15);
  const totalWidth = count * letterTargetWidth + (count - 1) * 12;
  const startX = (canvasWidth - totalWidth) / 2;

  return chars.map((char, index) => {
    const glyph = GLYPHS[char] || GLYPHS['3'];
    const letterX = startX + index * (letterTargetWidth + 12);
    const scaleX = letterTargetWidth / 100;
    const scaleY = targetHeight / 120;

    const frontPoints = glyph.outer.map(([x, y]) => ({
      x: letterX + x * scaleX,
      y: baselineY + y * scaleY
    }));

    const holes = glyph.holes
      ? glyph.holes.map(hole =>
          hole.map(([x, y]) => ({
            x: letterX + x * scaleX,
            y: baselineY + y * scaleY
          }))
        )
      : undefined;

    return {
      char,
      frontPoints,
      holes,
      bbox: {
        x: letterX,
        y: baselineY,
        width: letterTargetWidth,
        height: targetHeight
      }
    };
  });
}
